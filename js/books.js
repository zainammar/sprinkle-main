    // Remove BG
    var upload = document.getElementById('upload');
    var canvas = document.getElementById('canvas');
    var ctx = canvas.getContext('2d', { willReadFrequently: true });
    var link = document.getElementById('download');
    
    upload.addEventListener('change', e => {
      var file = e.target.files[0];
      if (!file) return;
      var img = new Image();
      img.onload = function() {
        ctx.clearRect(0, 0, canvas.width, canvas.height);
    
        // Draw image normally
        ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
    
        // Detect background color (top-left pixel)
        var imageData = ctx.getImageData(0, 0, canvas.width, canvas.height);
        var data = imageData.data;
        var r0 = data[0], g0 = data[1], b0 = data[2];
        var threshold = 25;
    
        // Remove similar color (background)
        for (let i = 0; i < data.length; i += 4) {
          var r = data[i], g = data[i + 1], b = data[i + 2];
          if (Math.abs(r - r0) < threshold && Math.abs(g - g0) < threshold && Math.abs(b - b0) < threshold) {
            data[i + 3] = 0;
          }
        }
        ctx.putImageData(imageData, 0, 0);
    
        // Apply circular mask (transparent outside)
        var temp = document.createElement('canvas');
        temp.width = temp.height = canvas.width;
        var tctx = temp.getContext('2d');
        tctx.clearRect(0, 0, temp.width, temp.height);
        tctx.save();
        tctx.beginPath();
        tctx.arc(temp.width / 2, temp.height / 2, temp.width / 1, 0, Math.PI * 2);
        tctx.clip();
        tctx.drawImage(canvas, 0, 0);
        tctx.restore();
    
        // Replace original with clipped result
        ctx.clearRect(0, 0, canvas.width, canvas.height);
        ctx.drawImage(temp, 0, 0);
    
        // âœ… Force PNG download (not WebP)
        link.href = canvas.toDataURL("image/png");
        link.download = "custom-emoji.png";
      };
      img.src = URL.createObjectURL(file);
    });
  